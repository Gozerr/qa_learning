alter table public.access_members enable row level security;
alter table public.articles enable row level security;

create or replace function public.is_admin()
returns boolean language sql security definer set search_path = public
as $$ select exists (select 1 from public.access_members where email = lower(auth.email()) and is_admin); $$;

create or replace function public.has_access()
returns boolean language sql security definer set search_path = public
as $$ select exists (select 1 from public.access_members where email = lower(auth.email())); $$;

drop policy if exists "members can read own access" on public.access_members;
create policy "members can read own access" on public.access_members for select to authenticated
using (email = lower(auth.email()) or public.is_admin());

drop policy if exists "admins manage members" on public.access_members;
create policy "admins manage members" on public.access_members for all to authenticated
using (public.is_admin()) with check (public.is_admin());

drop policy if exists "members read articles" on public.articles;
create policy "members read articles" on public.articles for select to authenticated
using (public.has_access());
